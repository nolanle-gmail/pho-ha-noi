const normLang = (l) => (LANGS.includes(String(l || '').toLowerCase()) ? String(l).toLowerCase() : DEFAULT_LANG);

// Everything the client needs to render & localize the form in all languages.
function ackContent() {
  const text = {};
  for (const l of LANGS) {
    const t = TEXT[l];
    text[l] = { name: t.name, title: t.title, intro: t.intro, points: t.points, agreementHeading: t.agreementHeading, agreement: t.agreement, checkbox: t.checkbox, ui: t.ui };
  }
  return { version: VERSION, default: DEFAULT_LANG, languages: LANGS.map(l => ({ code: l, label: TEXT[l].name })), text };
}

// Render a signed acknowledgment to a PDF Buffer (in the language signed).
// sig: { fullName, employeeName, employeeRef, signedAtLabel, ip, userAgent, ackId, lang }
async function renderAckPdf(sig) {
  const lang = normLang(sig.lang);
  const t = TEXT[lang], P = t.pdf;
  const blocks = [
    { h1: 'Phở Hà Nội' },
    { h2: t.title },
    { small: `${P.versionLabel} ${VERSION}` },
    { rule: true },
    { p: t.intro },
    { gap: 2 },
  ];
  t.points.forEach((pt, i) => blocks.push({ p: `${i + 1}.  ${pt}` }));
  blocks.push({ gap: 4 }, { h2: t.agreementHeading }, { p: t.agreement });
  blocks.push({ gap: 8 }, { rule: true }, { h2: P.signatureHeading });
  blocks.push({ kv: [P.signedBy, sig.fullName] });
  blocks.push({ kv: [P.employee, sig.employeeName + (sig.employeeRef ? `  (${sig.employeeRef})` : '')] });
  blocks.push({ kv: [P.dateTime, sig.signedAtLabel || ''] });
  blocks.push({ kv: [P.language, t.name] });
  blocks.push({ kv: [P.method, P.methodVal] });
  blocks.push({ kv: [P.ackId, sig.ackId ? String(sig.ackId) : '—'] });
  blocks.push({ gap: 10 });
  blocks.push({ small: P.footer + (sig.ip ? `  IP: ${sig.ip}.` : '') + (sig.userAgent ? `  ${sig.userAgent}` : '') });
  return textPdf(blocks, { title: `${t.title} (${VERSION})` });
}

module.exports = { POLICY, VERSION, LANGS, DEFAULT_LANG, normLang, ackContent, renderAckPdf, langName: (l) => TEXT[normLang(l)].name };
